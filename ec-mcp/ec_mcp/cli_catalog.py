READ_ONLY_PREFIXES = tuple(MONITORING)

DIAGNOSTIC = set(TROUBLESHOOTING)


def catalog_entries() -> list[dict[str, str]]:
    entries: list[dict[str, str]] = []
    for command in MONITORING:
        entries.append({"command": command, "category": "monitoring", "risk": "read"})
    for command in TROUBLESHOOTING:
        entries.append({"command": command, "category": "troubleshooting", "risk": "diagnostic"})
    for command in ALARM:
        entries.append({"command": command, "category": "alarm", "risk": "write"})
    for command in ADMINISTRATION:
        entries.append({"command": command, "category": "administration", "risk": "write"})
    for command in CONFIGURATION:
        entries.append({"command": command, "category": "configuration", "risk": "write"})
    for command in NEGATION:
        entries.append({"command": command, "category": "negation", "risk": "write"})
    return entries


def total_commands() -> int:
    return len(MONITORING) + len(TROUBLESHOOTING) + len(ALARM) + len(ADMINISTRATION) + len(CONFIGURATION) + len(NEGATION)
